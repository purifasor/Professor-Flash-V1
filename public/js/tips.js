  // pad to 500 chat tips by remixing (tip bank + suffix variants)
  function buildChatTips() {
    const base = CHAT_TIPS.slice();
    let i = 0;
    while (base.length < 500) {
      const src = CHAT_TIPS[i % CHAT_TIPS.length];
      const suffixes = [
        " Start today.",
        " Small steps, compounding results.",
        " Simple beats complex.",
        " Consistency is the multiplier.",
        " Measure it, improve it.",
        " One percent better daily.",
        " Make it a habit.",
        " Then repeat it.",
      ];
      base.push(src.replace(/\.$/, "") + suffixes[Math.floor(i / CHAT_TIPS.length) % suffixes.length]);
      i++;
    }
    return base.slice(0, 500);
  }

  const chatTips = buildChatTips();

  function typewriter(el, text, speed = 28) {
    el.textContent = "";
    let i = 0;
    clearTimeout(el._pfTypeTimer);
    const step = () => {
      el.textContent = text.slice(0, i);
      if (i < text.length) {
        i++;
        el._pfTypeTimer = setTimeout(step, speed);
      }
    };
    step();
  }

  function startRotation(el, tips, intervalMs = 15000) {
    if (!el) return;
    // clear any previous rotation bound to this element (old hero nodes)
    if (el._pfTimer) clearInterval(el._pfTimer);
    if (el._pfTypeTimer) clearTimeout(el._pfTypeTimer);
    let idx = Math.floor(Math.random() * tips.length);
    const show = () => {
      typewriter(el, tips[idx % tips.length]);
      idx++;
    };
    show();
    el._pfTimer = setInterval(show, intervalMs);
  }

  function start() {
    startRotation(document.getElementById("heroTip"), chatTips, 15000);
    startRotation(document.getElementById("peTip"), AGENT_TIPS, 9000);
  }

