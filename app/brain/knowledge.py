def search(question):
    """Find the best KB entry for a question.

    Returns (topic_text, score, answer) or (None, 0, None).
    Uses word-aware scoring so «تم» doesn't match «تمامی».
    """
    import re
    s = persian.soft(question)
    best, best_score = None, 0
    for entry in KB:
        score = 0
        for kw in entry["k"]:
            k = persian.soft(kw)
            if not k:
                continue
            if re.search(r"(?<!\w)" + re.escape(k) + r"(?!\w)", s):
                score += len(k)
            elif k in s:
                score += len(k) * 0.6  # substring hit counts less
        if score > best_score:
            best, best_score = entry, score
    if best and best_score >= 3:
        return best["k"][0], best_score, best["a"]
    return None, 0, None
